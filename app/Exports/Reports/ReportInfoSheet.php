<?php

namespace App\Exports\Reports;

use App\Models\SystemConfiguration;
use Illuminate\Support\Collection;
use Maatwebsite\Excel\Concerns\FromCollection;
use Maatwebsite\Excel\Concerns\ShouldAutoSize;
use Maatwebsite\Excel\Concerns\WithStyles;
use Maatwebsite\Excel\Concerns\WithTitle;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;

class ReportInfoSheet implements FromCollection, ShouldAutoSize, WithStyles, WithTitle
{
    /**
     * @param  array<string, mixed>  $info  Key-value pairs of report metadata
     * @param  array<string, string>  $filters  Human-readable filter labels
     */
    public function __construct(
        private readonly string $reportName,
        private readonly array $info = [],
        private readonly array $filters = [],
    ) {}

    public function title(): string
    {
        return 'Report Info';
    }

    public function collection(): Collection
    {
        $config = SystemConfiguration::getInstance();

        $rows = collect([
            ['Report Name', $this->reportName],
            ['Agency', $config->agency_name],
            ['Generated On', now()->format('F j, Y  g:i A')],
            ['', ''],
        ]);

        foreach ($this->info as $key => $value) {
            $rows->push([$key, $value]);
        }

        if (! empty($this->filters)) {
            $rows->push(['', '']);
            $rows->push(['── Filters Applied ──', '']);
            foreach ($this->filters as $key => $value) {
                $rows->push([$key, $value]);
            }
        } else {
            $rows->push(['Filters Applied', 'None (showing all data)']);
        }

        $rows->push(['', '']);
        $rows->push(['For Official Use Only', 'This report was automatically generated by the Records Management System.']);

        return $rows;
    }

    public function styles(Worksheet $sheet): void
    {
        // Header row style
        $sheet->getStyle('A1:B1')->getFont()->setBold(true)->setSize(13);
        $sheet->getStyle('A1:B3')->getFont()->setBold(true);

        // Key column
        $sheet->getStyle('A:A')->getFont()->setBold(true);
        $sheet->getStyle('A:A')->getFont()->getColor()->setARGB('FF334155');

        // Section header for filters
        $lastRow = $sheet->getHighestRow();
        for ($i = 1; $i <= $lastRow; $i++) {
            $cellVal = $sheet->getCell("A{$i}")->getValue();
            if (str_contains((string) $cellVal, '── Filters')) {
                $sheet->getStyle("A{$i}:B{$i}")->getFont()->setBold(true)->getColor()->setARGB('FF1e40af');
                $sheet->getStyle("A{$i}:B{$i}")->getFill()
                    ->setFillType(Fill::FILL_SOLID)
                    ->getStartColor()->setARGB('FFeff6ff');
            }
        }
    }
}
